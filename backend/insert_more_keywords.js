const insertKeywords = async () => {
  try {
    console.log('开始插入新热词...');
    
    let totalInserted = 0;
    
    for (const [nodeType, keywords] of Object.entries(newKeywords)) {
      console.log(`\n--- ${nodeType === 'disease' ? '疾病' : nodeType === 'symptom' ? '症状' : nodeType === 'drug' ? '药品' : '检查'} ---`);
      
      for (const keyword of keywords) {
        try {
          const exists = await pool.query('SELECT id FROM hot_keywords WHERE keyword = $1', [keyword]);
          if (exists.rows.length > 0) {
            console.log(`  ~ ${keyword} (已存在)`);
            continue;
          }
          
          const result = await pool.query(
            'INSERT INTO hot_keywords (keyword, keyword_type, node_type, weight, is_top, is_hidden) VALUES ($1, $2, $3, $4, $5, $6) RETURNING id',
            [keyword, nodeType, nodeType, Math.floor(Math.random() * 100) + 10, false, false]
          );
          
          if (result.rowCount > 0) {
            console.log(`  ✓ ${keyword}`);
            totalInserted++;
          }
        } catch (err) {
          console.log(`  ✗ ${keyword}: ${err.message}`);
        }
      }
    }
    
    console.log(`\n插入完成！共新增 ${totalInserted} 个热词`);
    
    const counts = await pool.query(
      'SELECT node_type, COUNT(*) as count FROM hot_keywords GROUP BY node_type ORDER BY count DESC'
    );
    
    console.log('\n各类型热词统计：');
    counts.rows.forEach(row => {
      const label = row.node_type === 'disease' ? '疾病' : row.node_type === 'symptom' ? '症状' : row.node_type === 'drug' ? '药品' : row.node_type === 'test' ? '检查' : row.node_type || '未知';
      console.log(`  ${label}: ${row.count} 个`);
    });
    
    const total = await pool.query('SELECT COUNT(*) as count FROM hot_keywords');
    console.log(`  总计: ${total.rows[0].count} 个热词`);
    
  } catch (err) {
    console.error('插入失败:', err);
  } finally {
    pool.end();
  }
};

insertKeywords();